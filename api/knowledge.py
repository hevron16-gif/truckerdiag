def _all_keys(entry: dict[str, Any]) -> list[str]:
    keys = [str(entry["code"])]
    for alias in entry.get("aliases") or []:
        keys.append(str(alias))
    return keys


def normalize_code(raw: str) -> str:
    """P0087, p-0087, SPN 157 FMI 1, 157/1 → компактный ключ."""
    s = (raw or "").strip().upper()
    s = s.replace("–", "-").replace("—", "-")
    compact = (
        s.replace(" ", "")
        .replace("-", "")
        .replace("_", "")
        .replace("/", "")
    )
    return compact


def _index() -> dict[str, dict[str, Any]]:
    idx: dict[str, dict[str, Any]] = {}
    for entry in KNOWLEDGE:
        for key in _all_keys(entry):
            idx[normalize_code(key)] = entry
    return idx


_INDEX = _index()


def lookup(code: str) -> dict[str, Any] | None:
    return _INDEX.get(normalize_code(code))


def format_entry(entry: dict[str, Any]) -> str:
    aliases = entry.get("aliases") or []
    alias_s = f" (также: {', '.join(aliases)})" if aliases else ""
    brands = ", ".join(entry.get("brands") or [])
    engines = ", ".join(entry.get("engines") or [])
    lines = [
        f"{entry['code']}{alias_s} — {entry['title']}",
        f"Техника: {brands}. Двигатели: {engines}.",
        entry["description"],
        f"Типичная тяжесть: {entry['severity']}. Типичное время: {entry['estimated_time_min']} мин.",
        "Причины:",
    ]
    for c in entry.get("causes") or []:
        oem = c.get("oem_part")
        oem_s = f"  OEM: {oem}" if oem else "  OEM: (нет в базе — не выдумывать)"
        lines.append(f"  • {c['cause']} ({c['probability']}%){oem_s}")
    lines.append("Проверки:")
    for step in entry.get("check_steps") or []:
        lines.append(f"  – {step}")
    return "\n".join(lines)


def format_service_manual() -> str:
    header = (
        "СЕРВИСНАЯ БАЗА TRUCKERDIAG — HOWO / SHACMAN / WEICHAI\n"
        "=====================================================\n"
        f"Записей: {len(KNOWLEDGE)}. OEM указан только там, где номер известен.\n"
    )
    return header + "\n\n".join(format_entry(e) for e in KNOWLEDGE)


def known_codes() -> list[str]:
    return [str(e["code"]) for e in KNOWLEDGE]
