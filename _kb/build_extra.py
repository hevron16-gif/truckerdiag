def load_rows():
    by = defaultdict(list)
    for line in TSV.read_text(encoding="utf-8").splitlines()[2:]:
        c = line.split("\t")
        if len(c) < 9:
            continue
        obd = c[-1].strip().upper()
        weichai = c[7].strip().upper()
        primary = weichai if re.fullmatch(r"[PUC][0-9A-F]{4}", weichai) else obd
        if not re.fullmatch(r"[PUC][0-9A-F]{4}", primary):
            continue
        if primary in SKIP:
            continue
        desc = re.sub(r"\s+", " ", c[1]).strip()
        if not desc or desc.lower().startswith("номер"):
            continue
        by[primary].append(
            {
                "desc": desc,
                "spn": c[2].strip(),
                "fmi": c[3].strip(),
                "weichai": weichai,
                "obd": obd,
            }
        )
    return by


def family(obd: str, desc: str) -> str:
    d = desc.lower()
    if obd.startswith("U") or "can" in d or "шин" in d:
        return "can"
    if "форсунк" in d or "впрыск" in d and "мочев" not in d:
        return "injector"
    if "рамп" in d or ("топлив" in d and "давлен" in d):
        return "rail"
    if "турбин" in d or "наддув" in d or "геометр" in d:
        return "turbo"
    if "egr" in d:
        return "egr"
    if "scr" in d or "мочев" in d or "аммиак" in d or "nox" in d:
        return "scr"
    if "dpf" in d or "саж" in d or "тверд" in d:
        return "dpf"
    if "педал" in d or "акселератор" in d:
        return "pedal"
    if "коленвал" in d:
        return "ckp"
    if "распред" in d:
        return "cmp"
    if "масл" in d:
        return "oil"
    if "охлажд" in d or "тосол" in d:
        return "coolant"
    if "аккумулятор" in d or "бортов" in d:
        return "battery"
    if "вентилятор" in d:
        return "fan"
    if "стартер" in d:
        return "starter"
    if "кондиционер" in d:
        return "ac"
    if "мочев" in d:
        return "scr"
    if ("сетк" in d or "обогрев" in d or "подогрев" in d) and "впуск" in d:
        return "intake_heat"
    if "скорост" in d and "автомобил" in d:
        return "vss"
    if "сцеплен" in d or "коробк" in d or "передач" in d:
        return "trans"
    if "тормоз" in d:
        return "brake"
    if "расходомер" in d or "масс" in d and "воздух" in d:
        return "maf"
    if "впуск" in d or "map" in d or "наддув" in d:
        return "map"
    if "датчик" in d or "сигнал" in d or "напряжен" in d:
        return "sensor"
    return "generic"


