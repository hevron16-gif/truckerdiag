def py_str(s: str) -> str:
    return s.replace("\\", "\\\\").replace('"', '\\"')


USED_ALIASES: set[str] = set()


def clean_desc(s: str) -> str:
    s = re.sub(r"\s+", " ", s).strip()
    s = re.sub(r"^[\d]+\s*", "", s)
    s = s.replace("датчикадавления", "датчика давления")
    s = s.replace("нижеминимального", "ниже минимального")
    s = s.replace("масимального", "максимального")
    s = s.replace("Отстутствует", "Отсутствует")
    s = s.replace("раход", "расход")
    s = s.replace("актутатора", "актуатора")
    return s.strip(" .")


