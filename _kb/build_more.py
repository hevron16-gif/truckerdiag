def from_howo_and_bus() -> list[dict]:
    out: list[dict] = []
    for row in HOWO_OFFICIAL:
        code, title, desc, c1, c2, c3, mins, sev = row
        if lookup(code):
            continue
        out.append(
            card(
                code,
                title,
                desc + " Официальная таблица Sinotruk Howo (DST-PC).",
                "Howo",
                "5",
                [],
                ["Howo", "Sitrak"],
                ["WD615", "WP10", "WP12", "MC11"],
                causes=[c1, c2, c3],
                steps=[
                    "Считать код сканером Howo/DST-PC, не только OBD.",
                    "Прозвонить указанную в описании цепь/пин.",
                    "Не менять ЭБУ, пока не исключён жгут.",
                ],
                severity=sev,
                time=mins,
            )
        )
    for code, aliases, title, desc, brands, engines, fam in BUS_AND_OTHER:
        if lookup(code) or any(lookup(a) for a in aliases if re.fullmatch(r"[PUBC][0-9A-F]{4}", a)):
            continue
        sev, mins, causes, steps = TPL[fam]
        out.append(
            card(
                code,
                title,
                desc,
                "Field",
                "2",
                [a for a in aliases if not lookup(a)],
                brands,
                engines,
                causes=causes,
                steps=steps,
                severity=sev,
                time=mins,
            )
        )
    return out


def main() -> None:
    packs = from_sitrak_other_systems() + from_howo_and_bus()
    # unique by code
    seen: set[str] = set()
    uniq = []
    for e in packs:
        if e["code"] in seen:
            continue
        seen.add(e["code"])
        uniq.append(e)
    OUT.write_text(json.dumps(uniq, ensure_ascii=False), encoding="utf-8")
    print(f"wrote {OUT} entries={len(uniq)}")
    from collections import Counter
    print("by system", Counter(e.get("source_system") for e in uniq).most_common(12))


if __name__ == "__main__":
    main()
