def card(
    code: str,
    title: str,
    desc: str,
    system: str,
    fmi: str,
    aliases: list[str] | None,
    brands: list[str],
    engines: list[str],
    causes: list[tuple[str, int]] | None = None,
    steps: list[str] | None = None,
    severity: str = "limited",
    time: int = 40,
) -> dict:
    if causes is None:
        causes = [
            (FMI_CAUSE.get(str(fmi), "Неисправность цепи или самого узла"), 45),
            ("Обрыв / коррозия разъёма или жгута указанного узла", 35),
            ("Неисправен сам датчик / клапан / блок", 20),
        ]
    if steps is None:
        steps = [
            f"Считать живые данные узла «{title[:50]}».",
            "Проверить питание, массу и разъём, осмотреть жгут.",
            "Сверить с сопутствующими кодами той же системы.",
        ]
    return {
        "code": code,
        "aliases": aliases or [],
        "brands": brands,
        "engines": engines,
        "title": title[:110],
        "description": desc,
        "causes": [
            {"cause": c, "probability": p, "oem_part": None} for c, p in causes
        ],
        "check_steps": steps,
        "severity": severity,
        "estimated_time_min": time,
        "source_system": system,
    }


def clean_sys(name: str) -> str:
    s = re.sub(r"[^A-Za-z0-9]+", "_", name or "Sitrak").strip("_")
    if s.lower().startswith("nanobcu"):
        return "NanoBCU"
    return s


def from_sitrak_other_systems() -> list[dict]:
    raw = json.loads((KB / "sitrak.json").read_text(encoding="utf-8"))
    out: list[dict] = []
    seen: set[str] = set()
    for x in raw:
        spn = str(x.get("spn") or "").strip()
        fmi = str(x.get("fmi") or "").strip()
        if not re.fullmatch(r"\d+", spn) or not re.fullmatch(r"\d+", fmi):
            continue
        desc = re.sub(r"\s+", " ", (x.get("description_ru") or "")).strip()
        if len(desc) < 8 or desc.lower().startswith("данные действительны"):
            continue
        sysname = x.get("system") or "Sitrak"
        key = f"SPN{spn}_FMI{fmi}"
        unique = f"{clean_sys(sysname)}_{key}"
        if unique in seen:
            continue
        if lookup(unique) is not None:
            continue
        # уже есть как общий SPN — берём только если это ДРУГАЯ система
        hit = lookup(key)
        if hit is None:
            continue
        hit_sys = str(hit.get("source_system") or "")
        if hit_sys == sysname or clean_sys(hit_sys) == clean_sys(sysname):
            continue
        seen.add(unique)
        aliases = [f"SPN {spn} FMI {fmi}", f"{spn}/{fmi}"]
        brands = ["Howo", "Sitrak", "Shacman"]
        engines = ["MC11", "MC13", "WP12", "WP13"]
        if "ABS" in sysname or "EBS" in sysname:
            engines = ["WD615", "WP10", "WP12", "MC11", "MC13"]
        if sysname == "Bosch":
            brands = ["Howo", "Sitrak", "Weichai"]
            engines = ["MC11", "MC13"]
        title = f"{sysname}: {desc}" if len(desc) < 80 else f"{sysname}: {desc[:77]}…"
        full = (
            f"{desc}. Sitrak/Howo, система {sysname}, SPN {spn} FMI {fmi}. "
            "Тот же SPN в другой системе — другая неисправность, не путать."
        )
        out.append(card(unique, title, full, sysname, fmi, aliases, brands, engines))
    return out


